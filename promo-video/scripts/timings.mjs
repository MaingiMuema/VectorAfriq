// Measures each narration clip with ffprobe and writes src/timings.ts
// containing line names, durations and computed start frames (30fps, with
// configurable gaps). Run AFTER gen-tts.mjs.
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const NARR = join(ROOT, "assets", "narration");
const FPS = 30;
const GAP_AFTER = {
  // seconds of lead-in/out silence around each line
  hook: 0.55, problem: 0.5, solution: 0.5, search: 0.45, ai: 0.45,
  services: 0.45, cta: 0.7, outro: 4.5, // 4.5s end-card hold with music riser
};

// story order (alphabetical dir listing is NOT the narrative order)
const ORDER = ["hook", "problem", "solution", "search", "ai", "services", "cta", "outro"];

const files = readdirSync(NARR).filter((f) => f.endsWith(".mp3")).sort();
const byName = new Map(
  files.map((f) => [f.replace(".mp3", ""), f])
);
const lines = ORDER.filter((n) => byName.has(n)).map((name) => {
  const f = byName.get(name);
  const dur = Number(
    execFileSync(
      "ffprobe",
      ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", join(NARR, f)],
      { encoding: "utf8" }
    ).trim()
  );
  return { name, dur };
});

// schedule sequentially
let cursor = 0;
const out = lines.map((l) => {
  const start = cursor;
  cursor += l.dur + (GAP_AFTER[l.name] ?? 0.6);
  return { name: l.name, start, duration: l.dur };
});

const total = cursor;
const compFrames = Math.ceil(total * FPS);
// round comp length to a clean multiple of 30 frames
const compFramesRounded = Math.ceil(compFrames / 30) * 30;

const ts = `
// AUTO-GENERATED by scripts/timings.mjs — do not edit by hand.
export const FPS = ${FPS};
export const VIDEO_DURATION = ${compFramesRounded}; // frames (${(compFramesRounded / FPS).toFixed(2)}s)
export const LINE_SECONDS: Record<string, number> = {
${lines.map((l) => `  ${JSON.stringify(l.name)}: ${l.dur.toFixed(3)},`).join("\n")}
};
export const SCHEDULE = [
${out.map((l) => `  { name: ${JSON.stringify(l.name)}, start: ${l.start.toFixed(3)}, duration: ${l.duration.toFixed(3)} },`).join("\n")}
];
`;

writeFileSync(join(ROOT, "src", "timings.ts"), ts);
console.log(`Total narration + gaps: ${total.toFixed(2)}s -> composition ${(compFramesRounded / FPS).toFixed(2)}s (${compFramesRounded} frames)`);

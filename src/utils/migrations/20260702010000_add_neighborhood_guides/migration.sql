-- Neighborhood Guides table for SEO-optimized location-based guides
-- These guides appear on search results pages to provide contextual neighborhood information
CREATE TABLE IF NOT EXISTS `neighborhood_guides` (
  `id` varchar(191) NOT NULL,
  `title` varchar(200) NOT NULL,
  `slug` varchar(200) NOT NULL,
  `excerpt` text COMMENT 'Short description shown in search results guide cards',
  `content` longtext NOT NULL COMMENT 'Rich HTML content from WYSIWYG editor',
  `image` varchar(500) DEFAULT NULL COMMENT 'Featured image URL',
  `metaTitle` varchar(200) DEFAULT NULL COMMENT 'SEO title tag override',
  `metaDescription` varchar(320) DEFAULT NULL COMMENT 'SEO meta description override',
  `locationType` enum('county','city','neighborhood') NOT NULL DEFAULT 'city' COMMENT 'Granularity level of the guide',
  `countyId` char(36) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL COMMENT 'County this guide is associated with',
  `cityId` varchar(191) DEFAULT NULL COMMENT 'City this guide is associated with (null = county-level)',
  `neighborhoodId` varchar(191) DEFAULT NULL COMMENT 'Neighborhood this guide is associated with (null = city/county-level)',
  `categories` text NOT NULL COMMENT 'JSON array of property category slugs this guide applies to (e.g. ["APARTMENTS","HOUSES"])',
  `published` tinyint(1) NOT NULL DEFAULT 0,
  `sortOrder` int NOT NULL DEFAULT 0 COMMENT 'Controls display order on search results',
  `authorId` varchar(191) NOT NULL,
  `createdAt` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `neighborhood_guides_slug_unique` (`slug`),
  KEY `neighborhood_guides_countyId_idx` (`countyId`),
  KEY `neighborhood_guides_cityId_idx` (`cityId`),
  KEY `neighborhood_guides_neighborhoodId_idx` (`neighborhoodId`),
  KEY `neighborhood_guides_published_idx` (`published`),
  KEY `neighborhood_guides_locationType_idx` (`locationType`),
  KEY `neighborhood_guides_sortOrder_idx` (`sortOrder`),
  CONSTRAINT `neighborhood_guides_countyId_fkey` FOREIGN KEY (`countyId`) REFERENCES `county`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `neighborhood_guides_cityId_fkey` FOREIGN KEY (`cityId`) REFERENCES `city`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `neighborhood_guides_neighborhoodId_fkey` FOREIGN KEY (`neighborhoodId`) REFERENCES `neighborhood`(`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `neighborhood_guides_authorId_fkey` FOREIGN KEY (`authorId`) REFERENCES `user`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

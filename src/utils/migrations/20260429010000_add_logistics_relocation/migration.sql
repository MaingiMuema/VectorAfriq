CREATE TABLE IF NOT EXISTS `mover_profiles` (
  `id` varchar(191) NOT NULL,
  `userId` varchar(191) NOT NULL,
  `businessName` varchar(191) NOT NULL,
  `contactPhone` varchar(64) NOT NULL,
  `contactEmail` varchar(191) DEFAULT NULL,
  `driversLicense` varchar(500) NOT NULL,
  `driversLicenseBackUrl` varchar(500) DEFAULT NULL,
  `idNumber` varchar(500) NOT NULL,
  `idBackUrl` varchar(500) DEFAULT NULL,
  `vehicleType` varchar(96) NOT NULL,
  `vehicleMake` varchar(96) DEFAULT NULL,
  `vehicleModel` varchar(96) DEFAULT NULL,
  `vehiclePlate` varchar(64) NOT NULL,
  `vehicleImageUrl` varchar(500) DEFAULT NULL,
  `vehicleCapacityKg` double NOT NULL,
  `vehicleVolumeCbm` double DEFAULT NULL,
  `baseLocation` varchar(191) NOT NULL,
  `serviceAreas` text,
  `baseRate` double NOT NULL DEFAULT 1500,
  `pricePerKm` double NOT NULL DEFAULT 120,
  `pricePerKg` double NOT NULL DEFAULT 8,
  `availabilityStatus` enum('AVAILABLE','BUSY','OFFLINE') NOT NULL DEFAULT 'AVAILABLE',
  `approvalStatus` enum('PENDING','APPROVED','REJECTED','SUSPENDED','BANNED') NOT NULL DEFAULT 'PENDING',
  `reviewNotes` text,
  `averageRating` double NOT NULL DEFAULT 0,
  `totalTrips` int NOT NULL DEFAULT 0,
  `currentLatitude` double DEFAULT NULL,
  `currentLongitude` double DEFAULT NULL,
  `lastLocationUpdate` datetime(3) DEFAULT NULL,
  `createdAt` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  UNIQUE KEY `mover_profiles_userId_key` (`userId`),
  KEY `mover_profiles_approval_idx` (`approvalStatus`),
  KEY `mover_profiles_location_idx` (`baseLocation`),
  CONSTRAINT `mover_profiles_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `user` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `relocation_requests` (
  `id` varchar(191) NOT NULL,
  `userId` varchar(191) NOT NULL,
  `moverId` varchar(191) DEFAULT NULL,
  `status` enum('PENDING_MOVER','COUNTERED','PRICE_AGREED','ACCEPTED','IN_TRANSIT','DELIVERED','CANCELLED','REJECTED') NOT NULL DEFAULT 'PENDING_MOVER',
  `pickupLocation` varchar(255) NOT NULL,
  `dropoffLocation` varchar(255) NOT NULL,
  `pickupLatitude` double DEFAULT NULL,
  `pickupLongitude` double DEFAULT NULL,
  `dropoffLatitude` double DEFAULT NULL,
  `dropoffLongitude` double DEFAULT NULL,
  `pickupTime` datetime(3) NOT NULL,
  `loadDescription` text,
  `loadWeightKg` double NOT NULL DEFAULT 0,
  `loadVolumeCbm` double DEFAULT NULL,
  `vehicleType` varchar(96) DEFAULT NULL,
  `estimatedDistanceKm` double DEFAULT NULL,
  `estimatedDurationMinutes` int DEFAULT NULL,
  `estimatedPrice` double DEFAULT NULL,
  `userOfferedPrice` double DEFAULT NULL,
  `moverCounterPrice` double DEFAULT NULL,
  `agreedPrice` double DEFAULT NULL,
  `notes` text,
  `moverResponseNotes` text,
  `createdAt` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (`id`),
  KEY `relocation_requests_user_idx` (`userId`),
  KEY `relocation_requests_mover_idx` (`moverId`),
  KEY `relocation_requests_status_idx` (`status`),
  CONSTRAINT `relocation_requests_userId_fkey` FOREIGN KEY (`userId`) REFERENCES `user` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT `relocation_requests_moverId_fkey` FOREIGN KEY (`moverId`) REFERENCES `mover_profiles` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
